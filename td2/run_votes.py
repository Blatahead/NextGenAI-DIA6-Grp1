#!/usr/bin/env python3
"""TD 2 step 1: run the k-of-n vote on the twenty TD 1 questions (stored real traces, no network).

From the repository root:  python td2/run_votes.py
- main panel: the fixed panel of atelier-vote.py (gpt-oss-120b, north-mini-code, qwen3.8-27b), k = 2 of 3;
- complementary view: the five TD 1 models, k = 3 of 5 (declared here, not required by the assignment).
The decision is taken first; the reference is compared afterwards and is never passed to the vote.
Writes td2/vote-decisions-2of3.csv, td2/vote-decisions-3of5.csv and td2/vote-decisions.md.
"""
import csv
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
spec = importlib.util.spec_from_file_location("atelier_vote", ROOT / "atelier-vote.py")
atelier = importlib.util.module_from_spec(spec)
spec.loader.exec_module(atelier)
vote = atelier.load_vote()

PANEL_3 = list(atelier.PANEL)
PANEL_5 = PANEL_3 + [("groq", "openai/gpt-oss-20b"), ("openrouter", "dots-studio/dots-3-note-preview:free")]
SHORT = {"openai/gpt-oss-120b": "120b", "cohere/north-mini-code:free": "cohere", "qwen/qwen3.8-27b": "qwen",
         "openai/gpt-oss-20b": "20b", "dots-studio/dots-3-note-preview:free": "dots"}


def family(question_type):
    return question_type


def run(rows, cases, panel, k, label):
    atelier.PANEL[:] = panel                    # proposals_for() reads the module-level panel
    out = []
    for case in cases:
        relevant = [r for r in rows if r["case_id"] == case["id"] and r["nature"] == "real"]
        reference = int(relevant[0]["reference"])
        props = atelier.proposals_for(rows, case["id"], "real")
        decision = vote(props, k)
        out.append({
            "case_id": case["id"], "family": case.get("type", ""), "panel": label, "n": len(panel), "k": k,
            "proposals": " ".join(f"{SHORT[p.model_requested]}={p.value if p.value is not None else 'ERR'}" for p in props),
            "decision": "consensus" if decision["consensus"] else "abstention",
            "value_kept": "" if decision["value"] is None else decision["value"],
            "votes": decision["votes"], "agreeing_members": " ".join(SHORT[m.split(":", 1)[1]] for m in decision["models"]),
            "reference": reference,
            "agrees_with_reference": ("yes" if decision["value"] == reference else "NO (wrong consensus)") if decision["consensus"] else "n/a (abstained)",
            "nature": "real", "evidence": "traces-td1.csv (last attempt per member)",
        })
    atelier.PANEL[:] = PANEL_3
    return out


def write_csv(path, rows):
    with open(path, "w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def summary(rows):
    cons = [r for r in rows if r["decision"] == "consensus"]
    right = [r for r in cons if r["agrees_with_reference"] == "yes"]
    wrong = [r["case_id"] for r in cons if r["agrees_with_reference"] != "yes"]
    abst = [r["case_id"] for r in rows if r["decision"] == "abstention"]
    return (f"{len(cons)}/{len(rows)} consensus ({len(right)} equal to the reference, {len(wrong)} wrong: {', '.join(wrong) or 'none'}); "
            f"{len(abst)}/{len(rows)} abstentions ({', '.join(abst) or 'none'})")


def markdown(rows):
    lines = ["| Case | Family | Proposals | Decision | Value | Votes | Agreeing | Reference | Agrees with reference |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['case_id']} | {r['family']} | {r['proposals']} | {r['decision']} | {r['value_kept']} | "
                     f"{r['votes']}/{r['n']} | {r['agreeing_members']} | {r['reference']} | {r['agrees_with_reference']} |")
    return "\n".join(lines)


def main():
    with open(ROOT / "traces-td1.csv", encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    cases = json.loads((ROOT / "questions-td1.json").read_text(encoding="utf-8"))["questions"]
    main_rows = run(rows, cases, PANEL_3, 2, "fixed 2-of-3")
    extra_rows = run(rows, cases, PANEL_5, 3, "five models 3-of-5")
    write_csv(ROOT / "td2" / "vote-decisions-2of3.csv", main_rows)
    write_csv(ROOT / "td2" / "vote-decisions-3of5.csv", extra_rows)
    text = ["# TD 2 — Decisions of the k-of-n vote on the twenty questions", "",
            "Generated by `python td2/run_votes.py` from `traces-td1.csv` (nature `real`, last attempt per member). "
            "Proposals: `ERR` = no executed value (error, invalid SQL or not executed): the member stays in n without voting. "
            "The reference is compared after the decision.", "",
            "## Fixed panel, k = 2 of 3 (gpt-oss-120b · north-mini-code · qwen3.8-27b) — required", "",
            "**" + summary(main_rows) + "**", "", markdown(main_rows), "",
            "## Complementary view: the five TD 1 models, k = 3 of 5 — declared by the sub-group, not required", "",
            "**" + summary(extra_rows) + "**", "", markdown(extra_rows), ""]
    (ROOT / "td2" / "vote-decisions.md").write_text("\n".join(text), encoding="utf-8")
    print("2-of-3:", summary(main_rows))
    print("3-of-5:", summary(extra_rows))


if __name__ == "__main__":
    main()
